"""Split the FULL CodeJudgeBench dataset into 150-question parallel configs (Gemini 2.5 Flash).

Unlike scripts/split_codejudgebench_parallel.py (which only re-chunks the *unfinished*
Qwen questions and seeds already-successful samples), this is a fresh run: Gemini has no
prior predictions, so every question is generated from scratch.

What it does:
  1. Reads the full dataset (codegen.jsonl, 2103 questions).
  2. Splits it into chunks of CHUNK_SIZE (=150), and for each chunk writes:
       - a chunk dataset file : src/datasets/CodeJudgeBench/chunks/codegen_part_XX.jsonl
       - a runnable config    : configs/codejudgebench_part_XX.yaml
         (Gemini 2.5 Flash, thinking budget 1024, max_new_tokens 16384; isolated
          generation_root so parallel runs never append to the same .jsonl)
  3. Regenerates run_all_parts.sh (parallel launcher).

Storage layout is unchanged: the model name (gemini_2.5_flash) is encoded into
experiment_relpath, so predictions land under
runs_v2/preds_parallel/part_XX/codejudgebench/gemini_2.5_flash/codejudgebench/.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DATASET = ROOT / "src" / "datasets" / "CodeJudgeBench" / "codegen.jsonl"
CHUNK_DS_DIR = ROOT / "src" / "datasets" / "CodeJudgeBench" / "chunks"
PARALLEL_ROOT = ROOT / "runs_v2" / "preds_parallel"
CHUNK_SIZE = 150

# OpenRouter key is read from the environment (see .env.example)
API_KEY = os.environ.get("OPENROUTER_API_KEY", "")


def part_cfg(ds_relpath: str, gen_root_relpath: str) -> dict:
    return {
        "model": {
            "provider": "openrouter",
            "model_id": "google/gemini-2.5-flash",
            "api_key": API_KEY,
            "max_new_tokens": 16384,
            "do_sample": True,
            "temperature": 0.0,
            "top_p": 0.95,
            "top_k": 20,
            "thinking": {
                "enabled": True,
                "mode": "budget",
                "budget": 1024,
                "exclude": True,
            },
        },
        "experiment": {
            "dataset": "codejudgebench",
            "dataset_path": ds_relpath,
            "num_tasks": "all",
            "num_samples": 10,
        },
        "prompt": {"template": "codejudgebench"},
        "codejudge": {"position_mode": "both"},
        "pipeline": {"generation_root": gen_root_relpath},
    }


def main() -> None:
    raw_lines: list[str] = []
    with DATASET.open(encoding="utf-8") as f:
        for line in f:
            if line.strip():
                raw_lines.append(line.rstrip("\n"))

    n = len(raw_lines)
    chunks = [
        list(range(i, min(i + CHUNK_SIZE, n)))
        for i in range(0, n, CHUNK_SIZE)
    ]
    print(f"total questions={n}  chunk_size={CHUNK_SIZE}  parts={len(chunks)}")

    CHUNK_DS_DIR.mkdir(parents=True, exist_ok=True)
    config_paths: list[str] = []

    for idx, chunk in enumerate(chunks, start=1):
        part = f"{idx:02d}"

        # 1) chunk dataset file (byte-identical raw lines)
        ds_path = CHUNK_DS_DIR / f"codegen_part_{part}.jsonl"
        ds_path.write_text(
            "\n".join(raw_lines[i] for i in chunk) + "\n", encoding="utf-8"
        )

        # 2) config (isolated generation_root for parallel safety)
        gen_root = PARALLEL_ROOT / f"part_{part}"
        cfg = part_cfg(
            str(ds_path.relative_to(ROOT)),
            str(gen_root.relative_to(ROOT)),
        )
        cfg_path = ROOT / "configs" / f"codejudgebench_part_{part}.yaml"
        with cfg_path.open("w", encoding="utf-8") as fh:
            fh.write(
                f"# AUTO-GENERATED by scripts/split_codejudgebench_gemini.py\n"
                f"# Part {part}/{len(chunks)} — {len(chunk)} questions "
                f"(dataset idx {chunk[0]}..{chunk[-1]}).\n"
                f"# Gemini 2.5 Flash, thinking budget 1024, max_new_tokens 16384; "
                f"isolated generation_root for parallel safety.\n"
            )
            yaml.safe_dump(cfg, fh, allow_unicode=True, sort_keys=False)
        config_paths.append(str(cfg_path.relative_to(ROOT)))
        print(f"part_{part}: {len(chunk)} questions -> {ds_path.relative_to(ROOT)}")

    # 3) run_all_parts.sh (parallel launcher)
    runner = ROOT / "scripts" / "run_all_parts.sh"
    lines = ["#!/usr/bin/env bash", "set -euo pipefail", f'cd "{ROOT}"', ""]
    for cp in config_paths:
        lines.append(
            f"python -m src.pipeline_v2.preds --config {cp} "
            f"> {cp.replace('configs/', 'scripts/').replace('.yaml', '.log')} 2>&1 &"
        )
    lines += ["", "wait", 'echo "all parts done"', ""]
    runner.write_text("\n".join(lines), encoding="utf-8")
    runner.chmod(0o755)

    print(f"\nWrote {len(chunks)} configs. Launch all in parallel with:")
    print("  bash scripts/run_all_parts.sh")


if __name__ == "__main__":
    main()
