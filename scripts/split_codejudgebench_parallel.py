"""Split the *unfinished* CodeJudgeBench questions into N parallel-safe configs.

What it does:
  1. Reads the dataset + the existing prediction file.
  2. Finds every question whose fwd/rev * num_samples judgements are NOT all `success`.
  3. Splits those questions into chunks of CHUNK_SIZE (default 100), and for each chunk writes:
       - a chunk dataset file        : src/datasets/CodeJudgeBench/chunks/codegen_part_XX.jsonl
       - a runnable config           : configs/codejudgebench_part_XX.yaml
         (same model/sampling/position settings; isolated generation_root so parallel
          runs never append to the same .jsonl)
       - a seeded prediction file    : <generation_root>/.../tem_..._k_20.jsonl
         pre-filled with the already-successful samples for that chunk's questions, so
         `resume` only generates the missing ones.
  4. Writes run_all_parts.sh (parallel launcher) and merge_parts.py (merge back for eval).

Re-runnable: regenerates configs/seeds from the current state of the prediction file.
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

from src.pipeline_v2.generation_core import experiment_relpath, prediction_filename

ROOT = Path(__file__).resolve().parents[1]
BASE_CONFIG = ROOT / "configs" / "codejudgebench.yaml"
DATASET = ROOT / "src" / "datasets" / "CodeJudgeBench" / "codegen.jsonl"
ORIG_PRED = (
    ROOT
    / "runs_v2/preds/codejudgebench/qwen3_coder_next/codejudgebench"
    / "tem_0_top_p_0.95_top_k_20.jsonl"
)
CHUNK_SIZE = 100
PARALLEL_ROOT = ROOT / "runs_v2" / "preds_parallel"
CHUNK_DS_DIR = ROOT / "src" / "datasets" / "CodeJudgeBench" / "chunks"


def load_base_cfg() -> dict:
    return yaml.safe_load(BASE_CONFIG.read_text(encoding="utf-8"))


def orderings(cfg: dict) -> list[bool]:
    mode = str((cfg.get("codejudge", {}) or {}).get("position_mode", "both")).lower()
    if mode == "forward":
        return [False]
    if mode == "reverse":
        return [True]
    return [False, True]


def main() -> None:
    cfg = load_base_cfg()
    num_samples = int(cfg["experiment"].get("num_samples", 10))
    tags = ["rev" if r else "fwd" for r in orderings(cfg)]

    # --- dataset lines (keep raw line text so chunk files are byte-identical) ---
    raw_lines: list[str] = []
    keys: list[tuple[str, str]] = []
    with DATASET.open(encoding="utf-8") as f:
        for idx, line in enumerate(f):
            if not line.strip():
                continue
            it = json.loads(line)
            raw_lines.append(line.rstrip("\n"))
            keys.append((str(it.get("question_id", idx)), str(it.get("response_model", "unknown"))))

    # --- latest record per sample_id from the existing prediction file ---
    latest: dict[str, dict] = {}
    if ORIG_PRED.exists():
        with ORIG_PRED.open(encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                d = json.loads(line)
                sid = d.get("sample_id")
                if sid:
                    latest[sid] = d

    def question_done(qid: str, rm: str) -> bool:
        for tag in tags:
            for s in range(num_samples):
                rec = latest.get(f"{qid}__{rm}__{tag}::{s}")
                if not rec or rec.get("status") != "success":
                    return False
        return True

    remaining = [i for i, (qid, rm) in enumerate(keys) if not question_done(qid, rm)]
    print(f"total questions={len(keys)}  remaining={len(remaining)}")

    # --- chunk + emit ---
    CHUNK_DS_DIR.mkdir(parents=True, exist_ok=True)
    chunks = [remaining[i : i + CHUNK_SIZE] for i in range(0, len(remaining), CHUNK_SIZE)]
    config_paths: list[str] = []

    for n, chunk in enumerate(chunks, start=1):
        part = f"{n:02d}"
        # 1) chunk dataset file
        ds_path = CHUNK_DS_DIR / f"codegen_part_{part}.jsonl"
        ds_path.write_text(
            "\n".join(raw_lines[i] for i in chunk) + "\n", encoding="utf-8"
        )

        # 2) config (isolated generation_root keeps parallel runs from colliding)
        gen_root = PARALLEL_ROOT / f"part_{part}"
        part_cfg = json.loads(json.dumps(cfg))  # deep copy
        part_cfg["experiment"]["dataset_path"] = str(
            ds_path.relative_to(ROOT)
        )
        part_cfg["experiment"]["num_tasks"] = "all"
        part_cfg.setdefault("pipeline", {})["generation_root"] = str(
            gen_root.relative_to(ROOT)
        )
        cfg_path = ROOT / "configs" / f"codejudgebench_part_{part}.yaml"
        with cfg_path.open("w", encoding="utf-8") as fh:
            fh.write(
                f"# AUTO-GENERATED by scripts/split_codejudgebench_parallel.py\n"
                f"# Part {part}/{len(chunks)} — {len(chunk)} remaining questions "
                f"(dataset idx {chunk[0]}..{chunk[-1]}).\n"
                f"# Same model/sampling/position settings as codejudgebench.yaml; "
                f"isolated generation_root for parallel safety.\n"
            )
            yaml.safe_dump(part_cfg, fh, allow_unicode=True, sort_keys=False)
        config_paths.append(str(cfg_path.relative_to(ROOT)))

        # 3) seed the part's prediction file with already-successful samples,
        #    so `resume` only generates the gaps.
        seed_path = gen_root / experiment_relpath(part_cfg) / prediction_filename(part_cfg)
        seed_path.parent.mkdir(parents=True, exist_ok=True)
        seeded = 0
        with seed_path.open("w", encoding="utf-8") as out:
            for i in chunk:
                qid, rm = keys[i]
                for tag in tags:
                    for s in range(num_samples):
                        rec = latest.get(f"{qid}__{rm}__{tag}::{s}")
                        if rec and rec.get("status") == "success":
                            out.write(json.dumps(rec, ensure_ascii=False) + "\n")
                            seeded += 1
        print(f"part_{part}: {len(chunk)} questions, seeded {seeded} success samples")

    # --- run_all_parts.sh ---
    runner = ROOT / "scripts" / "run_all_parts.sh"
    lines = ["#!/usr/bin/env bash", "set -euo pipefail", f'cd "{ROOT}"', ""]
    for cp in config_paths:
        lines.append(
            f"python -m src.pipeline_v2.preds --config {cp} "
            f"> {cp.replace('configs/', 'scripts/').replace('.yaml', '.log')} 2>&1 &"
        )
    lines += ["", "wait", 'echo "all parts done"', ""]
    runner.write_text("\n".join(lines), encoding="utf-8")
    runner.chmod(0o755)

    # --- merge_parts.py ---
    merge = ROOT / "scripts" / "merge_parts.py"
    merge.write_text(
        '''"""Merge all part prediction files (+ the original) into the canonical
preds path for eval. latest_by_sample dedupes; task_id is globally unique."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
ORIG = ROOT / "runs_v2/preds/codejudgebench/qwen3_coder_next/codejudgebench/tem_0_top_p_0.95_top_k_20.jsonl"
PARTS = sorted((ROOT / "runs_v2/preds_parallel").glob("part_*/codejudgebench/qwen3_coder_next/codejudgebench/tem_0_top_p_0.95_top_k_20.jsonl"))

latest = {}
order = []
for src in [ORIG, *PARTS]:
    if not src.exists():
        continue
    with src.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            d = json.loads(line)
            sid = d.get("sample_id")
            if not sid:
                continue
            if sid not in latest:
                order.append(sid)
            latest[sid] = d

with ORIG.open("w", encoding="utf-8") as out:
    for sid in order:
        out.write(json.dumps(latest[sid], ensure_ascii=False) + "\\n")
print(f"merged {len(order)} samples from {1 + len(PARTS)} files -> {ORIG}")
''',
        encoding="utf-8",
    )

    print(f"\nWrote {len(chunks)} configs. Launch all in parallel with:")
    print("  bash scripts/run_all_parts.sh")
    print("After they finish, merge for eval with:")
    print("  python scripts/merge_parts.py")


if __name__ == "__main__":
    main()
